def f(x, nd=2):
    """きれいな数の文字列（整数なら小数点なし）。"""
    x = round(x, nd)
    return str(int(x)) if x == int(x) else str(x)


def num(cat, unit, title, diff, body, ans, wrongs, expl, u):
    """数値の4択。ans とまちがい候補を、単位つきの文字列にして出す。"""
    seen = {f(ans)}
    ws = []
    for w in wrongs:
        s = f(w)
        if s not in seen and w > 0:
            seen.add(s); ws.append(s)
    k = 2
    while len(ws) < 3:                      # 候補が足りなければ倍数で補う
        s = f(ans * k)
        if s not in seen:
            seen.add(s); ws.append(s)
        k += 1
    qa(cat, unit, title, diff, body, f(ans) + u, [w + u for w in ws[:3]], expl)


