import os
import re
from gen_problems import Rng, tex2plain, LABELS

R = Rng(20261104)
OUT = []
_count = {}


def _add(cat, unit, diff, title, body, answer, expl, choices):
    key = (cat, unit)
    _count[key] = _count.get(key, 0) + 1
    plain = tex2plain(body) + "　" + "　".join(f"{LABELS[i]} {tex2plain(c)}" for i, c in enumerate(choices))
    OUT.append(dict(id=f"u-{unit}-{_count[key]}", category=cat, difficulty=diff, title=title, body=body,
                    answer=answer, explanation=expl, plain=plain, choices=choices, unit=unit))


def qa(cat, unit, title, diff, body, correct, wrongs, expl):
    opts = [correct] + list(wrongs)
    assert len(opts) == 4 and len(set(opts)) == 4, (unit, body)
    R.shuffle(opts)
    _add(cat, unit, diff, title, body, opts.index(correct), expl, opts)


