def pairs_both(cat, unit, title, diff, rows, q_fwd, q_rev, wrongs_n=3):
    """(表記, 意味) の表から、「表記→意味」「意味→表記」の2問ずつ作る。"""
    for a, b in rows:
        others = [r for r in rows if r[0] != a and r[1] != b]
        R.shuffle(others)
        qa(cat, unit, title, diff, q_fwd.format(a), b, [o[1] for o in others[:3]], f"{a}：{b}")
        others = [r for r in rows if r[0] != a and r[1] != b]
        R.shuffle(others)
        qa(cat, unit, title, diff, q_rev.format(b), a, [o[0] for o in others[:3]], f"{a}：{b}")


