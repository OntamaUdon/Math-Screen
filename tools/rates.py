WORD_ENJA = {"w_basic": 8.5, "w_std": 6.0, "w_adv": 4.2}
WORD_JAEN = {"w_basic": 7.0, "w_std": 4.5, "w_adv": 3.0}
IDIOM = (5.0, 3.5)     # 熟語：英→和、和→英


def _word(p):
    body = p["body"]
    if body.endswith("の意味として正しいものを選べ。"):
        en, enja = body[1:body.index("」")], True
    else:
        en, enja = p["choices"][p["answer"]], False
    if " " in en:
        base = IDIOM[0] if enja else IDIOM[1]
        return base
    base = (WORD_ENJA if enja else WORD_JAEN)[p["unit"]]
    adj = max(-1.0, min(0.8, -(len(en) - 6) * 0.15))      # 長い単語ほど難しい
    return base + adj


def assign(problems):
    """各問題に p['rate']（0〜10、小数第1位）を付ける。"""
    diffs = collections.defaultdict(list)
    for p in problems:
        diffs[(p["unit"], p["title"])].append(p["difficulty"])
    mean = {k: sum(v) / len(v) for k, v in diffs.items()}
    for p in problems:
        if p["category"] == "eng_word" and p["unit"] in WORD_ENJA:
            r = _word(p)
        else:
            base = TITLE_RATE.get(p["title"])
            if base is None: base = UNIT_RATE[p["unit"]]
            # 同じ種類の中で、私が付けたラベル（1〜3）が違うものだけ、平均からの差を0.8ずつずらす
            r = base + (mean[(p["unit"], p["title"])] - p["difficulty"]) * 0.8
        p["rate"] = round(max(2.0, min(9.8, r)), 1)
