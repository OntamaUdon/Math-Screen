def f(x):
    return str(int(x)) if float(x) == int(x) else str(x)


def num(cat, unit, title, diff, body, ans, wrongs, expl, suffix=""):
    """整数や小数の4択。まちがい候補が足りなければ、倍数で補う。"""
    seen = {f(ans)}
    ws = []
    for w in wrongs:
        s = f(w)
        if s not in seen and w > 0:
            seen.add(s); ws.append(s)
    k = 2
    while len(ws) < 3:
        s = f(ans * k)
        if s not in seen:
            seen.add(s); ws.append(s)
        k += 1
    qa(cat, unit, title, diff, body, f(ans) + suffix, [w + suffix for w in ws[:3]], expl)


