"""数学以外の教科（英語・社会・理科）の問題。tools/build_problems.py から呼ばれる。

- 4択問題（answer は正解の番号 0〜3）と、理科の計算問題（整数で答える）。
- 事実は、教科書にのっている基本的なことだけを選んでいる。公開前に、ご自身でも確認してください。
- 選択肢の並びは、自前の乱数で決めるので、毎回同じになる（CI の差分確認のため）。
"""
from gen_problems import Rng, fmt, tex2plain, LABELS

R = Rng(20261103)
OUT = []


def _add(cat, diff, title, body, answer, expl, choices=None):
    n = sum(1 for p in OUT if p["category"] == cat) + 1
    plain = tex2plain(body)
    if choices is not None:
        plain += "　" + "　".join(f"{LABELS[i]} {tex2plain(c)}" for i, c in enumerate(choices))
    p = dict(id=f"s-{cat}-{n}", category=cat, difficulty=diff, title=title, body=body, answer=answer,
             explanation=expl, plain=plain)
    if choices is not None: p["choices"] = choices
    OUT.append(p)


def _qa(cat, diff, title, body, correct, wrongs, expl):
    opts = [correct] + list(wrongs)
    assert len(opts) == 4 and len(set(opts)) == 4, body
    R.shuffle(opts)
    _add(cat, diff, title, body, opts.index(correct), expl, opts)


